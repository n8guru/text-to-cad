"""Generate BOM27.md from hardware.json + out/parts_manifest.json. One source of truth, no retyping.

    python cad/make_bom.py
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

ROOT = Path(__file__).resolve().parents[1]
HW = json.loads((ROOT / "hardware.json").read_text())
MAN = json.loads((ROOT / "out" / "parts_manifest.json").read_text())

PURCHASED_ORDER = [
    "rotary_latch", "striker", "release_cable", "release_handle", "t_handle", "hinge",
    "gas_strut", "bulb_seal", "locating_pin_round", "locating_pin_diamond", "bushing",
    "ball_plunger", "chmsl", "harness_tap",
]


def esc(x):
    return str(x).replace("|", "\\|") if x is not None else "—"


def purchased_rows():
    rows = []
    for key in PURCHASED_ORDER:
        h = HW[key]
        qty = h.get("qty") or h.get("qty_cables") or h.get("length_m") or 1
        unit = "m" if key == "bulb_seal" else "off"
        rows.append((
            h.get("role", key).split(".")[0][:58],
            esc(h.get("manufacturer")),
            esc(h.get("pn") or h.get("pn_hatch")),
            f"{qty:g} {unit}",
            h.get("status", "?"),
            h.get("provenance", "?"),
            esc(h.get("source_where") or h.get("source_url", ""))[:70],
        ))
    return rows


def custom_rows():
    seen, rows = set(), []
    for m in MAN:
        if m["status"] != "CUSTOM":
            continue
        fam = m["part"].split("__")[-1]
        for tag in ("_2", "_3"):
            if fam.endswith(tag):
                fam = fam[: -len(tag)]
        fam = fam.split("-")[0]
        if fam in seen:
            continue
        seen.add(fam)
        rows.append((fam, m["material"], m["process"], m["finish"], f'{m["mass_kg"]:.3f}'))
    return sorted(rows)


def counts():
    c = defaultdict(int)
    for m in MAN:
        fam = m["part"].split("__")[-1]
        for tag in ("_2", "_3"):
            if fam.endswith(tag):
                fam = fam[: -len(tag)]
        c[fam] += 1
    return c


def main():
    out = []
    a = out.append
    a("# Step 27 — orderable BOM\n")
    a("Generated by `cad/make_bom.py` from `hardware.json` (vendor truth) and "
      "`out/parts_manifest.json` (geometry truth). Do not hand-edit; edit the sources.\n")
    a("**Nothing here has been purchased.** Every row is a specification, not an order.\n")

    a("\n## 1. Purchased parts\n")
    a("| Function | Manufacturer | Part number | Qty | Status | Provenance | Source |")
    a("|---|---|---|---|---|---|---|")
    for r in purchased_rows():
        a("| " + " | ".join(r) + " |")

    a("\n### 1a. Ancillary purchased items called out by the same datasheets\n")
    anc = [
        ("Fork-bolt support plate (raises R4-30 ultimate to 14 230 N)", "Southco",
         HW["rotary_latch"]["support_plate_pn"], "10 off"),
        ("Cable retainer clip, trigger end", "Southco",
         HW["release_cable"]["retainer_clip_trigger"], "10 off"),
        ("Cable retainer clip, lever end", "Southco",
         HW["release_cable"]["retainer_clip_lever"], "10 off"),
        ("Cable splitter, one handle to two latches", "Southco",
         HW["release_handle"]["splitter_pn"], "5 off"),
        ("Panel-mounted cable bracket", "Southco",
         HW["release_handle"]["panel_bracket_pn"], "10 off"),
        ("E3 flange gasket — REQUIRED for the IP65 rating", "Southco",
         HW["t_handle"]["gasket_pn"], "2 off"),
        ("E3 spur washer — round-hole install in composite", "Southco",
         HW["t_handle"]["spur_washer_pn"], "2 off"),
        ("Spare CH751 keys", "Southco", HW["t_handle"]["spare_keys_pn"], "1 set"),
        ("Gas-strut ball stud, Dia 10 ball on M8", HW["gas_strut"]["ball_stud"]["manufacturer"],
         HW["gas_strut"]["ball_stud"]["pn"], "4 off"),
        ("Ball socket spare, metal / plastic", "Stabilus",
         f'{HW["gas_strut"]["ball_socket_spares"]["metal"]} / '
         f'{HW["gas_strut"]["ball_socket_spares"]["plastic"]}', "as spares"),
        ("12 V upfitter mating connector", "Aptiv", HW["harness_tap"]["pn"], "1 off"),
        ("12 V upfitter terminals", "Aptiv", HW["harness_tap"]["terminal_pn"], "per connector"),
    ]
    a("| Item | Manufacturer | Part number | Qty |")
    a("|---|---|---|---|")
    for r in anc:
        a("| " + " | ".join(esc(x) for x in r) + " |")

    a("\n## 2. Machined / fabricated parts\n")
    a("Material, process, finish and mass come from the geometry model; drawings are in "
      "`step27/drawings/`.\n")
    a("| Part | Material | Process | Finish | Mass (kg ea.) |")
    a("|---|---|---|---|---|")
    for r in custom_rows():
        a("| " + " | ".join(esc(x) for x in r) + " |")

    a("\n### 2a. Critical tolerances (these are what make four sockets interchangeable)\n")
    import geom as G  # noqa: E402
    a("| Feature | Tolerance (mm) | Why it is on the drawing |")
    a("|---|---|---|")
    why = {
        "bushing_true_position": "sets whether one module drops into any of the four sockets",
        "land_flatness": "sets the seal's closed gap around the whole perimeter",
        "ledge_lip_height": "sets whether the module sits flush after it is hung",
        "seal_groove_depth": "legacy name; now the seal-rib height, sets bulb deflection",
        "module_profile": "sets the visible 4 mm shut line",
        "hinge_axis_straightness": "sets whether the hatch leaf binds through its swing",
        "latch_pattern": "Southco panel preparation, 38.1 +/-0.3 hole pitch",
    }
    for k, v in G.TOL.items():
        a(f"| {k} | {v} | {why.get(k, '')} |")
    a(f"| compression limiter thickness | 7.40 +0 / -0.05 | "
      f"this dimension IS the seal compression |")

    a("\n## 3. Part count from the geometry model\n")
    c = counts()
    a(f"{len(MAN)} part instances, {len(c)} distinct part families, "
      f"{sum(m['mass_kg'] for m in MAN):.1f} kg of Step 27 hardware "
      f"(the carbon shell itself is not in this number).\n")

    a("\n## 4. What is NOT resolved — these block ordering\n")
    for key in sorted(HW):
        if key.startswith("_") or not isinstance(HW[key], dict):
            continue
        h = HW[key]
        if h.get("open"):
            a(f"- **{key}** ({h.get('status')}) — {h['open']}")
        if h.get("CRITICAL"):
            a(f"- **{key}** — {h['CRITICAL']}")
    a("\n### Status rollup\n")
    st = defaultdict(list)
    for key, h in HW.items():
        if not key.startswith("_") and isinstance(h, dict) and "status" in h:
            st[h["status"]].append(key)
    for k in sorted(st):
        a(f"- **{k}** ({len(st[k])}): {', '.join(sorted(st[k]))}")

    a("\n## 5. Standing caveat\n")
    a("No purchase order has been raised, no supplier contacted, no quote requested. "
      "Prices are deliberately absent: an unquoted price is a guess, and a guess in a BOM is "
      "worse than a blank. FEA, prototype fit, real-truck calibration, fabrication release and "
      "Nate-only design approval all remain later gates.")

    (ROOT / "BOM27.md").write_text("\n".join(out) + "\n")
    print(f"BOM27.md written: {len(purchased_rows())} purchased families, "
          f"{len(custom_rows())} fabricated families, {len(MAN)} instances")


if __name__ == "__main__":
    main()
